function issue(
  seriesKey,
  issueNumber,
  sourceIssueReference = null,
  sourceRangeReference = null,
  candidateIssueId = null,
  selectionNote = null,
) {
  const series = SERIES[seriesKey];
  if (!series) throw new Error(`Unknown series key: ${seriesKey}`);
  return {
    sourceIssueReference: sourceIssueReference ?? `${series.title} #${issueNumber}`,
    sourceRangeReference,
    normalizedSeriesTitle: series.title,
    seriesYear: series.year,
    issueNumber: issueNumber == null ? null : String(issueNumber),
    seriesId: series.id,
    candidateIssueId,
    manualSeriesSelectionApproved: Boolean(series.selectionNote),
    selectionNote,
  };
}

